def write_catalog(root: Path = OUT) -> None:
    metas = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(root.glob("*/scene.json"))]
    lines = [HEAD, "## Сцены", ""]
    counts: dict[str, int] = {}
    for m in metas:
        counts[m["family"]] = counts.get(m["family"], 0) + 1
    lines.append("Сцен " + str(len(metas)) + ": " + ", ".join(f"{f} — {n}" for f, n in counts.items()) + ".")
    lines.append("")
    lines.append("| Семейство | О чём |")
    lines.append("|---|---|")
    lines += [f"| {f} | {FAMILIES[f]} |" for f in counts]
    lines += ["", "| id | Семейство | Что проверяет | Источник | Точек |", "|---|---|---|---|---|"]
    for m in metas:
        src = m["source"]
        where = SOURCE[src["kind"]] + (f", {src['city']}" if src.get("city") else "")
        lines.append(f"| {m['id']} | {m['family']} | {m['title']} | {where} | {len(m['points'])} |")
    covered: dict[str, list[str]] = {}
    for m in metas:
        for r in m["rules"]:
            covered.setdefault(r, []).append(m["id"])
    lines += ["", "## Чем покрыты правила", "", "| Правило | Суть | Сцены |", "|---|---|---|"]
    for rid, text in RULES.items():
        scenes = covered.get(rid, [])
        lines.append(f"| {rid} | {text} | {', '.join(scenes) if scenes else 'нет'} |")
    unknown = sorted(set(covered) - set(RULES))
    if unknown:
        lines += ["", "Пункты без описания: " + ", ".join(unknown)]
    (root / "CATALOG.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
